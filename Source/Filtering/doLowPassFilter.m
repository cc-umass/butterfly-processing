function epochedEEG = doLowPassFilter(epochedEEG)

loadFilteringConstants;

epochedEEG = pop_basicfilter(epochedEEG, getChannelsToFilter(epochedEEG), ...
    'Filter', 'lowpass', ...
    'Design', 'butter', ...
    'Cutoff', lowPassHz, ...
    'Order', lowPassOrder, ...
    'RemoveDC', 'off');
epochedEEG = eeg_checkset(epochedEEG);
butterflyLog('  low-pass %g Hz Butterworth order %d (epoched)', lowPassHz, lowPassOrder);
end
