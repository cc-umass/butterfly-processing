function subjectEEG = doHighPassFilter(subjectEEG)

loadFilteringConstants;

subjectEEG = pop_basicfilter(subjectEEG, getChannelsToFilter(subjectEEG), ...
    'Filter', 'highpass', ...
    'Design', 'butter', ...
    'Cutoff', highPassHz, ...
    'Order', highPassOrder, ...
    'RemoveDC', 'on', ...
    'Boundary', []);
subjectEEG = eeg_checkset(subjectEEG);
butterflyLog('  high-pass %.1f Hz Butterworth order %d', highPassHz, highPassOrder);
end
