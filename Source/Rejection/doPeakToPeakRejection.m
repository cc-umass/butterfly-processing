function rejectedEpochs = doPeakToPeakRejection(epochedEEG)

loadRejectionConstants;

channels = {epochedEEG.chanlocs.labels};
epochCount = epochedEEG.trials;
scalpChannels = find(~ismember(upper(channels), peripheralChannels));
epochedEEG = pop_artmwppth(epochedEEG, ...
    'Twindow', testWindowMs, ...
    'Threshold', ptpThresholdUv, ...
    'Windowsize', ptpWindowMs, ...
    'Windowstep', ptpStepMs, ...
    'Channel', scalpChannels, ...
    'Flag', 1, ...
    'Review', 'off');
rejectedEpochs = epochedEEG.reject.rejmanual > 0;
butterflyLog('  ptp > %g uV (%d ms window, %d ms step, %d ch): %d of %d epochs flagged (%.1f%%)', ...
    ptpThresholdUv, ptpWindowMs, ptpStepMs, numel(scalpChannels), sum(rejectedEpochs), epochCount, 100 * sum(rejectedEpochs) / epochCount);
end
