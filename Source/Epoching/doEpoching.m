function epochedEEG = doEpoching(subjectEEG)

loadEpochingConstants;

epochedEEG = pop_creabasiceventlist(subjectEEG, ...
    'Eventlist', eventListFile, ...
    'BoundaryString', {'boundary'}, ...
    'BoundaryNumeric', {-99}, ...
    'Warning', 'off');
epochedEEG = pop_binlister(epochedEEG, ...
    'BDF', binDescriptorFile, ...
    'ExportEL', eventListFile, ...
    'ImportEL', 'no', ...
    'SendEL2', 'EEG&Text', ...
    'Warning', 'off');
epochedEEG = pop_epochbin(epochedEEG, epochWindowMs, 'none');
epochedEEG = eeg_checkset(epochedEEG);
end
